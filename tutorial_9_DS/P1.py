# String Demo

name = "raM"

print(f"Type: {type(name)}")
print(f"Data: {name}")

# find char at index
# print(f"???? Char: {name[-4]}")
print(f"ThirLast/First Char: {name[-3]}")
print(f"SecondLast Char: {name[-2]}")
print(f"Last Char: {name[-1]}")
print(f"First Char: {name[0]}")
print(f"Second Char: {name[1]}")
print(f"Third Char: {name[2]}")
# print(f"Fourth Char: {name[3]}")

# Finding length
print(f"Total length: {len(name)}")
print(f"Last Char: {name[len(name)-1]}")
print(f"SecondLast Char: {name[len(name)-2]}")
print(f"ThirdLast/first Char: {name[len(name)-3]}")

# string methods
print(f"Upper: {name.upper()}")
print(f"Lower: {name.lower()}")
print(f"Capitalise: {name.capitalize()}")

